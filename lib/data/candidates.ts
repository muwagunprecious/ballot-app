export function getCandidatesByOffice(office: string): Candidate[] {
  return INITIAL_CANDIDATES.filter(c => c.office.toUpperCase() === office.toUpperCase());
}

export function getCandidatesForRace(params: {
  office: string;
  stateCode?: string;
  senatorialDistrictId?: string;
  federalConstituencyId?: string;
}): Candidate[] {
  const { office, stateCode, senatorialDistrictId, federalConstituencyId } = params;
  
  return INITIAL_CANDIDATES.filter(c => {
    if (c.office.toUpperCase() !== office.toUpperCase()) return false;
    
    if (office === 'PRESIDENT') {
      return true;
    }
    
    if (office === 'GOVERNOR') {
      if (!stateCode) return true;
      return c.stateCode?.toUpperCase() === stateCode.toUpperCase();
    }
    
    if (office === 'SENATOR') {
      if (senatorialDistrictId) {
        return c.senatorialDistrictId?.toUpperCase() === senatorialDistrictId.toUpperCase();
      }
      if (stateCode) {
        return c.stateCode?.toUpperCase() === stateCode.toUpperCase();
      }
      return true;
    }
    
    if (office === 'REPRESENTATIVE') {
      if (federalConstituencyId) {
        return c.federalConstituencyId?.toUpperCase() === federalConstituencyId.toUpperCase();
      }
      if (senatorialDistrictId) {
        return c.senatorialDistrictId?.toUpperCase() === senatorialDistrictId.toUpperCase();
      }
      if (stateCode) {
        return c.stateCode?.toUpperCase() === stateCode.toUpperCase();
      }
      return true;
    }
    
    return true;
  });
}

export function getCandidateById(id?: string): Candidate | undefined {
  if (!id) return undefined;
  return INITIAL_CANDIDATES.find(c => c.id === id);
}
