export function getPartyById(id?: string): PoliticalParty | undefined {
  if (!id) return undefined;
  return POLITICAL_PARTIES.find(
    p =>
      p.id.toLowerCase() === id.toLowerCase() ||
      p.code.toLowerCase() === id.toLowerCase() ||
      p.acronym.toLowerCase() === id.toLowerCase()
  );
}

export function getPartyByAcronym(acronym?: string): PoliticalParty | undefined {
  if (!acronym) return undefined;
  return POLITICAL_PARTIES.find(p => p.acronym.toLowerCase() === acronym.toLowerCase());
}

export function getPartyColor(acronym: string): string {
  const party = getPartyByAcronym(acronym);
  return party ? party.color : '#20C878';
}

export function getPartyLogoUrl(acronym: string): string | undefined {
  const party = getPartyByAcronym(acronym);
  return party?.logoUrl;
}
