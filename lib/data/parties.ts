export function getPartyById(id: string): PoliticalParty | undefined {
  return POLITICAL_PARTIES.find(p => p.id === id || p.code.toLowerCase() === id.toLowerCase() || p.acronym.toLowerCase() === id.toLowerCase());
}

export function getPartyColor(acronym: string): string {
  const party = POLITICAL_PARTIES.find(p => p.acronym.toLowerCase() === acronym.toLowerCase());
  return party ? party.color : '#20C878';
}
